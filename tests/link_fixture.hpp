#pragma once
#include <cstdint>
#include <vector>
#include <algorithm>
inline std::vector<std::uint8_t> linked_gb_rom(){
    std::vector<std::uint8_t> rom(32768);rom[0x100]=0xC3;rom[0x101]=0x50;rom[0x102]=1;
    // Real SM83 program: C001 selects internal/external clock, JOYP supplies
    // each outgoing byte, C000 receives peer data, C002 counts transfers.
    const std::vector<std::uint8_t> program{
        0xF3,0x31,0xFE,0xFF,0x3E,0x10,0xE0,0x00,
        0xF0,0x00,0xE0,0x01,0xFA,0x01,0xC0,0xF6,0x80,0xE0,0x02,
        0xF0,0x02,0xCB,0x7F,0x20,0xFA,
        0xF0,0x01,0xEA,0x00,0xC0,0x21,0x02,0xC0,0x34,0x18,0xE4};
    std::copy(program.begin(),program.end(),rom.begin()+0x150);return rom;
}
